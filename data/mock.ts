export function enrichWithUser<T extends { authorId: string; author?: User }>(
  items: T[],
  users: User[] = mockUsers,
): T[] {
  return items.map((item) => ({
    ...item,
    author: users.find((u) => u._id === item.authorId),
  }));
}

export function enrichConversations(conversations: Conversation[]): Conversation[] {
  return conversations.map((conv) => ({
    ...conv,
    participants: conv.participantIds
      .map((id) => mockUsers.find((u) => u._id === id))
      .filter(Boolean) as User[],
    lastMessage: mockMessages[conv._id]?.at(-1),
  }));
}
